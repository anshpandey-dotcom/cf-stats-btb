val releaseKeyAlias = signingValue("VERITY_KEY_ALIAS")
val releaseKeyPassword = signingValue("VERITY_KEY_PASSWORD") ?: releaseStorePassword
val hasSigning = releaseStorePath != null && releaseStorePassword != null && releaseKeyAlias != null

